package com.bank.core.enums;

/**
 * Направление операции относительно текущего пользователя.
 */
public enum OperationDirection {
    /** Деньги пришли на счёт пользователя. */
    INCOME,
    /** Деньги ушли со счёта пользователя. */
    EXPENSE,
    /** Перевод между собственными счетами — не считается ни тратой, ни доходом. */
    INTERNAL
}
